const axios = require("axios");

jest.mock("axios");

const { buildVideoVerdictNarrative, normalizeNarrationInput } = require("./verdictNarrationService");

describe("verdictNarrationService", () => {
    beforeEach(() => {
        jest.resetAllMocks();
        process.env.GEMINI_API_KEY = "test-key";
        process.env.GEMINI_MODEL = "gemini-2.0-flash";
        process.env.GEMINI_VERDICT_TIMEOUT_MS = "2000";
    });

    afterEach(() => {
        delete process.env.GEMINI_API_KEY;
        delete process.env.GEMINI_MODEL;
        delete process.env.GEMINI_VERDICT_TIMEOUT_MS;
    });

    test("returns Gemini narrative when JSON schema is valid", async () => {
        axios.post.mockResolvedValueOnce({
            data: {
                candidates: [
                    {
                        content: {
                            parts: [
                                {
                                    text: JSON.stringify({
                                        sentences: [
                                            "The video is flagged as AI Generated by the final model verdict.",
                                            "Confidence is high with synthetic patterns stronger than biological cues.",
                                        ],
                                    }),
                                },
                            ],
                        },
                    },
                ],
            },
        });

        const payload = {
            verdict: "fake",
            confidence: 0.86,
            prediction: 0.73,
            rppg_result: { is_biological: false },
            analysis: {
                stage_health: "ok",
                verdict_reason: "High synthetic-likelihood detected",
            },
        };

        const result = await buildVideoVerdictNarrative(payload);

        expect(result.source).toBe("gemini");
        expect(result.sentences).toHaveLength(2);
        expect(result.input.verdict).toBe("fake");
        expect(result.input.fusion_score).toBeCloseTo(0.73, 6);

        const [, requestBody, requestConfig] = axios.post.mock.calls[0];
        expect(requestConfig.timeout).toBe(2000);
        const promptText = requestBody.contents[0].parts[0].text;
        expect(promptText).toContain('"verdict":"fake"');
        expect(promptText).toContain('"fusion_score":0.73');
        expect(promptText).not.toContain("file_url");
    });

    test("falls back to template narrative when Gemini times out", async () => {
        axios.post.mockRejectedValueOnce({ code: "ECONNABORTED" });

        const result = await buildVideoVerdictNarrative({
            verdict: "real",
            confidence: 0.78,
            prediction: 0.22,
            analysis: { verdict_reason: "Biological consistency signals dominant" },
        });

        expect(result.source).toBe("template");
        expect(Array.isArray(result.sentences)).toBe(true);
        expect(result.sentences.length).toBeGreaterThanOrEqual(2);
    });

    test("falls back to template when Gemini output violates schema", async () => {
        axios.post.mockResolvedValueOnce({
            data: {
                candidates: [
                    {
                        content: {
                            parts: [
                                {
                                    text: JSON.stringify({
                                        sentences: ["Guaranteed authentic content with 100% certainty."],
                                    }),
                                },
                            ],
                        },
                    },
                ],
            },
        });

        const result = await buildVideoVerdictNarrative({
            verdict: "real",
            confidence: 0.63,
            prediction: 0.31,
            analysis: { verdict_reason: "Signals are stable" },
        });

        expect(result.source).toBe("template");
        expect(result.sentences[0]).toContain("final model verdict");
    });

    test("normalizes student-criteria input fields", () => {
        const normalized = normalizeNarrationInput({
            verdict: "inconclusive",
            confidence: 67,
            prediction: 51,
            rppg_result: { is_biological: true },
            analysis: {
                stage_health: { facemesh: "ok", rppg: "ok", fusion: "ok" },
                verdict_reason: "Near-boundary score",
            },
        });

        expect(normalized.confidence).toBeCloseTo(0.67, 6);
        expect(normalized.fusion_score).toBeCloseTo(0.51, 6);
        expect(normalized.is_biological).toBe(true);
        expect(normalized.stage_health).toContain("facemesh:ok");
        expect(normalized.verdict_reason).toBe("Near-boundary score");
    });
});
